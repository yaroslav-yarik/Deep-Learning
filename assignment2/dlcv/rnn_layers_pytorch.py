def temporal_affine_forward(x, w, b):
    """Прямой проход для временного аффинного слоя.

    На вход подаётся набор D-мерных векторов, организованных в мини-батч из N
    последовательностей длины T. Аффинная функция преобразует каждый из этих
    векторов в новый вектор размерности M.

    Входные данные:
    - x: входные данные формы (N, T, D)
    - w: веса формы (D, M)
    - b: смещения формы (M,)

    Возвращает:
    - out: выходные данные формы (N, T, M)
    """
    N, T, D = x.shape
    M = b.shape[0]
    out = (x.reshape(N * T, D) @ w).reshape(N, T, M) + b
    return out


def temporal_softmax_loss(x, y, mask, verbose=False):
    """Временная версия softmax-функции потерь для RNN.

    Предполагается, что на каждом шаге по времени последовательности длины T
    делается предсказание по словарю размера V; обработка идёт по мини-батчу
    размера N. Вход x содержит оценки для всех элементов словаря на всех шагах
    по времени, а y — индексы эталонных элементов на каждом шаге. На каждом
    шаге по времени используется функция потерь перекрёстной энтропии
    (cross-entropy); потери суммируются по всем шагам по времени и
    усредняются по мини-батчу.

    Дополнительная сложность: на некоторых шагах по времени выход модели может
    понадобиться игнорировать, поскольку в мини-батч могли быть объединены
    последовательности разной длины, дополненные токенами <NULL>. Аргумент
    mask указывает, какие элементы должны учитываться в функции потерь.

    Входные данные:
    - x: входные оценки формы (N, T, V)
    - y: эталонные индексы формы (N, T), каждый элемент которых лежит в
         диапазоне 0 <= y[i, t] < V
    - mask: логический массив формы (N, T), где mask[i, t] показывает,
      учитываются ли оценки x[i, t] в функции потерь.

    Возвращает:
    - loss: скаляр — значение функции потерь
    """

    N, T, V = x.shape

    x_flat = x.reshape(N * T, V)
    # Индексы классов для cross_entropy должны иметь тип int64 (long); на Windows
    # np.random.randint по умолчанию выдаёт int32.
    y_flat = y.reshape(N * T).long()
    mask_flat = mask.reshape(N * T)

    loss = torch.nn.functional.cross_entropy(x_flat, y_flat, reduction='none')
    loss = loss * mask_flat.float()
    loss = loss.sum() / N

    return loss
