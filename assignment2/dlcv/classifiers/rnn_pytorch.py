import numpy as np
import torch
from ..rnn_layers_pytorch import *


class CaptioningRNN:
    """
    CaptioningRNN генерирует подписи по признакам изображений с помощью
    рекуррентной нейронной сети.

    RNN получает входные векторы размера D, размер словаря равен V, длина
    последовательностей — T, размерность скрытого состояния RNN — H,
    размерность векторов слов — W, размер мини-батча — N.

    Обратите внимание: в CaptioningRNN регуляризация не используется.
    """

    def __init__(
        self,
        word_to_idx,
        input_dim=512,
        wordvec_dim=128,
        hidden_dim=128,
        cell_type="rnn",
        dtype=torch.float32,
    ):
        """
        Создаёт новый экземпляр CaptioningRNN.

        Входные данные:
        - word_to_idx: словарь Python, задающий словарь модели (vocabulary).
          Содержит V элементов и сопоставляет каждой строке (слову) уникальное
          целое число из диапазона [0, V).
        - input_dim: размерность D входных векторов признаков изображений.
        - wordvec_dim: размерность W векторов слов.
        - hidden_dim: размерность H скрытого состояния RNN.
        - cell_type: тип рекуррентной ячейки; в этой лабораторной работе
          используется только простая RNN: 'rnn'.
        - dtype: тип данных PyTorch; для обучения используйте torch.float32,
          а для численной проверки градиента — torch.float64.
        """
        if cell_type != "rnn":
            raise ValueError('Недопустимое значение cell_type "%s"' % cell_type)

        self.cell_type = cell_type
        self.dtype = dtype
        self.word_to_idx = word_to_idx
        self.idx_to_word = {i: w for w, i in word_to_idx.items()}
        self.params = {}

        vocab_size = len(word_to_idx)

        self._null = word_to_idx["<NULL>"]
        self._start = word_to_idx.get("<START>", None)
        self._end = word_to_idx.get("<END>", None)

        # Инициализируем векторы слов
        self.params["W_embed"] = torch.randn(vocab_size, wordvec_dim)
        self.params["W_embed"] /= 100

        # Инициализируем параметры проекции признаков CNN -> скрытое состояние
        self.params["W_proj"] = torch.randn(input_dim, hidden_dim)
        self.params["W_proj"] /= np.sqrt(input_dim)
        self.params["b_proj"] = torch.zeros(hidden_dim)

        # Инициализируем параметры RNN
        self.params["Wx"] = torch.randn(wordvec_dim, hidden_dim)
        self.params["Wx"] /= np.sqrt(wordvec_dim)
        self.params["Wh"] = torch.randn(hidden_dim, hidden_dim)
        self.params["Wh"] /= np.sqrt(hidden_dim)
        self.params["b"] = torch.zeros(hidden_dim)

        # Инициализируем веса преобразования выхода RNN в оценки слов словаря
        self.params["W_vocab"] = torch.randn(hidden_dim, vocab_size)
        self.params["W_vocab"] /= np.sqrt(hidden_dim)
        self.params["b_vocab"] = torch.zeros(vocab_size)

        # Приводим параметры к нужному типу данных (dtype)
        for k, v in self.params.items():
            self.params[k] = v.to(self.dtype)

    def loss(self, features, captions):
        """
        Вычисляет значение функции потерь RNN на этапе обучения. На вход
        подаются признаки изображений и эталонные подписи к ним; с помощью RNN
        вычисляется значение потерь, по которому затем находятся
        градиенты по всем параметрам.

        Входные данные:
        - features: входные признаки изображений формы (N, D)
        - captions: эталонные подписи — целочисленный массив формы (N, T + 1),
          каждый элемент которого лежит в диапазоне 0 <= captions[i, t] < V

        Возвращает:
        - loss: скаляр — значение функции потерь
        """
        # Разрезаем подписи на две части: captions_in содержит все слова, кроме
        # последнего, и подаётся на вход RNN; captions_out содержит все слова,
        # кроме первого, — именно их RNN должна сгенерировать. Части сдвинуты
        # друг относительно друга на одну позицию, потому что, получив слово t,
        # RNN должна выдать слово (t+1). Первым элементом captions_in будет
        # токен <START>, а первым элементом captions_out — первое слово подписи.
        captions_in = captions[:, :-1]
        captions_out = captions[:, 1:]

        # Это вам понадобится
        mask = captions_out != self._null

        # Веса и смещение аффинного преобразования признаков изображения
        # в начальное скрытое состояние
        W_proj, b_proj = self.params["W_proj"], self.params["b_proj"]

        # Матрица векторных представлений слов (word embedding)
        W_embed = self.params["W_embed"]

        # Параметры RNN: веса «вход → скрытое состояние», «скрытое состояние →
        # скрытое состояние» и смещения
        Wx, Wh, b = self.params["Wx"], self.params["Wh"], self.params["b"]

        # Веса и смещение преобразования скрытого состояния в оценки слов словаря.
        W_vocab, b_vocab = self.params["W_vocab"], self.params["b_vocab"]

        loss = 0.0
        ############################################################################
        # Реализовано: Реализуйте прямой проход для CaptioningRNN.                        #
        # Во время прямого прохода нужно сделать следующее:                        #
        # (1) С помощью аффинного преобразования вычислить по признакам            #
        #     изображений начальное скрытое состояние. Должен получиться           #
        #     массив формы (N, H).                                                 #
        # (2) С помощью слоя векторного представления слов (word embedding)        #
        #     преобразовать слова из captions_in из индексов в векторы;            #
        #     получится массив формы (N, T, W).                                    #
        # (3) С помощью простой RNN обработать последовательность векторов         #
        #     входных слов и получить векторы скрытых состояний для всех шагов     #
        #     по времени — массив формы (N, T, H).                                 #
        # (4) С помощью (временного) аффинного преобразования вычислить по         #
        #     скрытым состояниям оценки для всех слов словаря на каждом шаге       #
        #     по времени — массив формы (N, T, V).                                 #
        # (5) С помощью (временной) softmax-функции потерь вычислить потери        #
        #     относительно captions_out, игнорируя с помощью маски mask            #
        #     (см. выше) позиции, где выходное слово — <NULL>.                     #
        #                                                                          #
        # Убедитесь, что ваша реализация не зависит от типа данных (dtype)         #
        # входных тензоров.                                                        #
        #                                                                          #
        # О регуляризации весов и их градиентов можно не беспокоиться!             #
        #                                                                          #
        # Обратный проход реализовывать тоже не нужно.                             #
        ############################################################################

        features = features.to(dtype=W_proj.dtype, device=W_proj.device)
        h0 = affine_forward(features, W_proj, b_proj)
        words = word_embedding_forward(captions_in.to(W_embed.device), W_embed)
        h = rnn_forward(words, h0, Wx, Wh, b)
        scores = temporal_affine_forward(h, W_vocab, b_vocab)
        loss = temporal_softmax_loss(scores, captions_out.to(scores.device), mask.to(scores.device))
        ############################################################################
        #                            КОНЕЦ ВАШЕГО КОДА                             #
        ############################################################################

        return loss

    def sample(self, features, max_length=30):
        """
        Выполняет прямой проход модели на этапе тестирования, генерируя
        (сэмплируя) подписи по входным векторам признаков.

        На каждом шаге по времени мы получаем векторное представление текущего
        слова, подаём его вместе с предыдущим скрытым состоянием на вход RNN и
        получаем следующее скрытое состояние, по скрытому состоянию вычисляем
        оценки для всех слов словаря и выбираем в качестве следующего слова
        слово с наибольшей оценкой. Начальное скрытое состояние вычисляется
        аффинным преобразованием входных признаков изображения, а начальное
        слово — это токен <START>.

        Входные данные:
        - features: массив входных признаков изображений формы (N, D).
        - max_length: максимальная длина T генерируемых подписей.

        Возвращает:
        - captions: массив формы (N, max_length) со сгенерированными подписями,
          каждый элемент которого — целое число из диапазона [0, V). Первым
          элементом captions должно быть первое сгенерированное слово, а не
          токен <START>.
        """
        N = features.shape[0]
        captions = torch.full((N, max_length), self._null, dtype=torch.long,
                              device=self.params["W_embed"].device)

        # Распаковываем параметры
        W_proj, b_proj = self.params["W_proj"], self.params["b_proj"]
        W_embed = self.params["W_embed"]
        Wx, Wh, b = self.params["Wx"], self.params["Wh"], self.params["b"]
        W_vocab, b_vocab = self.params["W_vocab"], self.params["b_vocab"]

        ###########################################################################
        # Реализовано: Реализуйте генерацию подписей на этапе тестирования. Скрытое      #
        # состояние RNN нужно инициализировать, применив к входным признакам      #
        # изображений обученное аффинное преобразование. Первым словом,           #
        # которое подаётся на вход RNN, должен быть токен <START>; его индекс     #
        # хранится в переменной self._start. На каждом шаге по времени нужно:     #
        # (1) получить векторное представление предыдущего слова с помощью        #
        #     обученных векторов слов (word embedding);                           #
        # (2) сделать шаг RNN по предыдущему скрытому состоянию и векторному      #
        #     представлению текущего слова и получить следующее скрытое           #
        #     состояние;                                                          #
        # (3) применить к следующему скрытому состоянию обученное аффинное        #
        #     преобразование и получить оценки для всех слов словаря;             #
        # (4) выбрать в качестве следующего слова слово с наибольшей оценкой      #
        #     и записать его (индекс слова) в соответствующую позицию             #
        #     переменной captions.                                                #
        #                                                                         #
        # Для простоты можно не прекращать генерацию после того, как выбран       #
        # токен <END>, но при желании можно и прекращать.                         #
        #                                                                         #
        # ПОДСКАЗКА: функцию rnn_forward здесь использовать не получится —        #
        # нужно вызывать rnn_step_forward в цикле.                                #
        #                                                                         #
        # ПРИМЕЧАНИЕ: эта функция по-прежнему работает с мини-батчами.            #
        ###########################################################################

        with torch.no_grad():
            features = features.to(dtype=W_proj.dtype, device=W_proj.device)
            h = affine_forward(features, W_proj, b_proj)
            word = torch.full((N,), self._start, dtype=torch.long, device=W_embed.device)
            for t in range(max_length):
                x = word_embedding_forward(word, W_embed)
                h = rnn_step_forward(x, h, Wx, Wh, b)
                word = (h @ W_vocab + b_vocab).argmax(dim=1)
                captions[:, t] = word

        ############################################################################
        #                            КОНЕЦ ВАШЕГО КОДА                             #
        ############################################################################
        return captions
