def conv_forward_naive(x, w, b, conv_param):
    """Наивная реализация прямого прохода для свёрточного слоя.

    Вход состоит из N примеров, каждый из которых имеет C каналов, высоту H
    и ширину W. Каждый вход сворачивается с F различными фильтрами; каждый
    фильтр охватывает все C каналов и имеет высоту HH и ширину WW.

    Входные данные:
    - x: входные данные формы (N, C, H, W)
    - w: веса фильтров формы (F, C, HH, WW)
    - b: смещения формы (F,)
    - conv_param: словарь со следующими ключами:
      - 'stride': шаг — число пикселей между соседними рецептивными полями
        по горизонтали и по вертикали.
      - 'pad': число пикселей, на которое вход дополняется нулями.

    При дополнении (padding) нули нужно добавлять симметрично: по 'pad'
    нулей с каждой стороны вдоль осей высоты и ширины входа. Будьте
    внимательны: не изменяйте исходный вход x напрямую.

    Возвращает кортеж:
    - out: выходные данные формы (N, F, H', W'), где H' и W' вычисляются так:
      H' = 1 + (H + 2 * pad - HH) / stride
      W' = 1 + (W + 2 * pad - WW) / stride
    - cache: (x, w, b, conv_param)
    """
    stride, pad = conv_param['stride'], conv_param['pad']
    N, C, H, W = x.shape
    F, _, HH, WW = w.shape
    OH, OW = 1 + (H + 2 * pad - HH) // stride, 1 + (W + 2 * pad - WW) // stride
    padded = np.pad(x, ((0, 0), (0, 0), (pad, pad), (pad, pad)))
    out = np.empty((N, F, OH, OW), dtype=np.result_type(x, w, b))
    for i in range(OH):
        for j in range(OW):
            patch = padded[:, :, i * stride:i * stride + HH, j * stride:j * stride + WW]
            out[:, :, i, j] = np.einsum('nchw,fchw->nf', patch, w) + b
    return out, (x, w, b, conv_param)


def conv_backward_naive(dout, cache):
    """Наивная реализация обратного прохода для свёрточного слоя.

    Входные данные:
    - dout: градиенты, пришедшие сверху (upstream).
    - cache: кортеж (x, w, b, conv_param), как в conv_forward_naive

    Возвращает кортеж:
    - dx: градиент по x
    - dw: градиент по w
    - db: градиент по b
    """
    x, w, b, conv_param = cache
    stride, pad = conv_param['stride'], conv_param['pad']
    HH, WW = w.shape[2:]
    padded = np.pad(x, ((0, 0), (0, 0), (pad, pad), (pad, pad)))
    dx_padded, dw = np.zeros_like(padded), np.zeros_like(w)
    db = dout.sum(axis=(0, 2, 3))
    for i in range(dout.shape[2]):
        for j in range(dout.shape[3]):
            hs, ws = i * stride, j * stride
            patch = padded[:, :, hs:hs + HH, ws:ws + WW]
            dw += np.einsum('nf,nchw->fchw', dout[:, :, i, j], patch)
            dx_padded[:, :, hs:hs + HH, ws:ws + WW] += np.einsum('nf,fchw->nchw', dout[:, :, i, j], w)
    return dx_padded[:, :, pad:pad + x.shape[2], pad:pad + x.shape[3]], dw, db


def max_pool_forward_naive(x, pool_param):
    """Наивная реализация прямого прохода для слоя max-пулинга.

    Входные данные:
    - x: входные данные формы (N, C, H, W)
    - pool_param: словарь со следующими ключами:
      - 'pool_height': высота каждой области пулинга
      - 'pool_width': ширина каждой области пулинга
      - 'stride': расстояние между соседними областями пулинга

    Дополнение (padding) здесь не нужно; можно считать, что:
      - (H - pool_height) % stride == 0
      - (W - pool_width) % stride == 0

    Возвращает кортеж:
    - out: выходные данные формы (N, C, H', W'), где H' и W' вычисляются так:
      H' = 1 + (H - pool_height) / stride
      W' = 1 + (W - pool_width) / stride
    - cache: (x, pool_param)
    """
    PH, PW, stride = pool_param['pool_height'], pool_param['pool_width'], pool_param['stride']
    N, C, H, W = x.shape
    OH, OW = 1 + (H - PH) // stride, 1 + (W - PW) // stride
    out = np.empty((N, C, OH, OW), dtype=x.dtype)
    for i in range(OH):
        for j in range(OW):
            patch = x[:, :, i * stride:i * stride + PH, j * stride:j * stride + PW]
            out[:, :, i, j] = patch.max(axis=(2, 3))
    return out, (x, pool_param)


def max_pool_backward_naive(dout, cache):
    """Наивная реализация обратного прохода для слоя max-пулинга.

    Входные данные:
    - dout: градиенты, пришедшие сверху (upstream)
    - cache: кортеж (x, pool_param), как в прямом проходе.

    Возвращает:
    - dx: градиент по x
    """
    x, pool_param = cache
    PH, PW, stride = pool_param['pool_height'], pool_param['pool_width'], pool_param['stride']
    dx = np.zeros_like(x)
    for i in range(dout.shape[2]):
        for j in range(dout.shape[3]):
            hs, ws = i * stride, j * stride
            patch = x[:, :, hs:hs + PH, ws:ws + PW]
            mask = patch == patch.max(axis=(2, 3), keepdims=True)
            # Split the subgradient between tied maxima, as in the fast pooling layer.
            dx[:, :, hs:hs + PH, ws:ws + PW] += mask * (dout[:, :, i, j, None, None] / mask.sum(axis=(2, 3), keepdims=True))
    return dx


def spatial_batchnorm_forward(x, gamma, beta, bn_param):
    """Вычисляет прямой проход для пространственной батч-нормализации.

    Входные данные:
    - x: входные данные формы (N, C, H, W)
    - gamma: параметр масштаба формы (C,)
    - beta: параметр сдвига формы (C,)
    - bn_param: словарь со следующими ключами:
      - mode: 'train' или 'test'; обязательный ключ
      - eps: константа для численной устойчивости
      - momentum: константа для скользящего среднего / дисперсии. momentum=0
        означает, что на каждом шаге старая информация полностью
        отбрасывается, а momentum=1 — что новая информация никогда не
        учитывается. Значение по умолчанию momentum=0.9 хорошо работает
        в большинстве случаев.
      - running_mean: массив формы (C,) — скользящее среднее признаков
      - running_var: массив формы (C,) — скользящая дисперсия признаков

    Возвращает кортеж:
    - out: выходные данные формы (N, C, H, W)
    - cache: значения, необходимые для обратного прохода
    """
    N, C, H, W = x.shape
    out, cache = batchnorm_forward(x.transpose(0, 2, 3, 1).reshape(-1, C), gamma, beta, bn_param)
    return out.reshape(N, H, W, C).transpose(0, 3, 1, 2), cache


def spatial_batchnorm_backward(dout, cache):
    """Вычисляет обратный проход для пространственной батч-нормализации.

    Входные данные:
    - dout: градиенты, пришедшие сверху (upstream), формы (N, C, H, W)
    - cache: значения из прямого прохода

    Возвращает кортеж:
    - dx: градиент по входам формы (N, C, H, W)
    - dgamma: градиент по параметру масштаба формы (C,)
    - dbeta: градиент по параметру сдвига формы (C,)
    """
    N, C, H, W = dout.shape
    dx, dgamma, dbeta = batchnorm_backward(dout.transpose(0, 2, 3, 1).reshape(-1, C), cache)
    return dx.reshape(N, H, W, C).transpose(0, 3, 1, 2), dgamma, dbeta


def spatial_groupnorm_forward(x, gamma, beta, G, gn_param):
    """Вычисляет прямой проход для пространственной групповой нормализации.

    В отличие от нормализации по слою, групповая нормализация разбивает
    каждый пример на G непрерывных частей (групп подряд идущих каналов)
    и нормализует каждую из них независимо. Затем, так же как в
    батч-нормализации и нормализации по слою, к данным применяются сдвиг и
    масштабирование по каждому признаку (каналу).

    Входные данные:
    - x: входные данные формы (N, C, H, W)
    - gamma: параметр масштаба формы (1, C, 1, 1)
    - beta: параметр сдвига формы (1, C, 1, 1)
    - G: целое число — количество групп, на которые разбиваются каналы;
      должно быть делителем C
    - gn_param: словарь со следующими ключами:
      - eps: константа для численной устойчивости

    Возвращает кортеж:
    - out: выходные данные формы (N, C, H, W)
    - cache: значения, необходимые для обратного прохода
    """
    N, C, H, W = x.shape
    if G <= 0 or C % G:
        raise ValueError('G must be a positive divisor of the channel count')
    grouped = x.reshape(N, G, -1)
    inv_std = 1.0 / np.sqrt(grouped.var(axis=2, keepdims=True) + gn_param.get('eps', 1e-5))
    normalized = (grouped - grouped.mean(axis=2, keepdims=True)) * inv_std
    xhat = normalized.reshape(x.shape)
    out = gamma * xhat + beta
    return out, (normalized, inv_std, gamma, G)


def spatial_groupnorm_backward(dout, cache):
    """Вычисляет обратный проход для пространственной групповой нормализации.

    Входные данные:
    - dout: градиенты, пришедшие сверху (upstream), формы (N, C, H, W)
    - cache: значения из прямого прохода

    Возвращает кортеж:
    - dx: градиент по входам формы (N, C, H, W)
    - dgamma: градиент по параметру масштаба формы (1, C, 1, 1)
    - dbeta: градиент по параметру сдвига формы (1, C, 1, 1)
    """
    normalized, inv_std, gamma, G = cache
    N, C, H, W = dout.shape
    dgamma = np.sum(dout * normalized.reshape(dout.shape), axis=(0, 2, 3), keepdims=True)
    dbeta = np.sum(dout, axis=(0, 2, 3), keepdims=True)
    grad = (dout * gamma).reshape(N, G, -1)
    dx = inv_std * (grad - grad.mean(axis=2, keepdims=True) - normalized * (grad * normalized).mean(axis=2, keepdims=True))
    return dx.reshape(dout.shape), dgamma, dbeta
