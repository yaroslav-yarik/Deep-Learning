def dropout_forward(x, dropout_param):
    """Прямой проход для инвертированного dropout.

    Обратите внимание, что эта версия отличается от обычной (vanilla) версии
    dropout. Здесь p — вероятность сохранить выход нейрона, а не вероятность
    его обнулить. В инвертированном dropout масштабирование выполняется во
    время обучения: значения, которые не были обнулены, делятся на p, поэтому
    во время тестирования вход возвращается без изменений.

    Входные данные:
    - x: входные данные произвольной формы
    - dropout_param: словарь со следующими ключами:
      - p: параметр dropout. Каждый выход нейрона сохраняется с вероятностью p.
      - mode: 'test' или 'train'. В режиме train выполняется dropout;
        в режиме test вход просто возвращается без изменений.
      - seed: начальное значение (seed) генератора случайных чисел. Если
        передать seed, функция становится детерминированной — это нужно для
        проверки градиента, но не в реальных сетях.

    Выходные данные:
    - out: массив той же формы, что и x.
    - cache: кортеж (dropout_param, mask). В режиме обучения mask — маска
      dropout, на которую умножался вход; в режиме тестирования mask равна
      None.
    """
    p, mode = dropout_param["p"], dropout_param["mode"]
    if "seed" in dropout_param:
        np.random.seed(dropout_param["seed"])

    mask = None
    out = None

    if mode == "train":
        #######################################################################
        # TODO: Реализуйте прямой проход инвертированного dropout в режиме    #
        # обучения. Маску dropout сохраните в переменной mask.                #
        #######################################################################
        mask = (np.random.rand(*x.shape) < p) / p
        out = x * mask
        #######################################################################
        #                          КОНЕЦ ВАШЕГО КОДА                          #
        #######################################################################
    elif mode == "test":
        #######################################################################
        # TODO: Реализуйте прямой проход инвертированного dropout в режиме    #
        # тестирования.                                                       #
        #######################################################################
        out = x
        #######################################################################
        #                          КОНЕЦ ВАШЕГО КОДА                          #
        #######################################################################

    cache = (dropout_param, mask)
    out = out.astype(x.dtype, copy=False)

    return out, cache


