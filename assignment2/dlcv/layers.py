import numpy as np


def affine_forward(x, w, b):
    """Вычисляет прямой проход для аффинного (полносвязного) слоя.

    Вход x имеет форму (N, d_1, ..., d_k) и содержит мини-батч из N
    примеров, где каждый пример x[i] имеет форму (d_1, ..., d_k). Каждый
    вход нужно развернуть в вектор размерности D = d_1 * ... * d_k, а затем
    преобразовать его в выходной вектор размерности M.

    Входные данные:
    - x: массив numpy с входными данными формы (N, d_1, ..., d_k)
    - w: массив numpy весов формы (D, M)
    - b: массив numpy смещений формы (M,)

    Возвращает кортеж:
    - out: выход формы (N, M)
    - cache: (x, w, b)
    """
    out = None
    # Реализация из лабораторной работы 1.
    # Разворачиваем каждый пример в строку: (N, d_1, ..., d_k) -> (N, D)
    x_rows = x.reshape(x.shape[0], -1)
    out = x_rows.dot(w) + b
    cache = (x, w, b)
    return out, cache


def affine_backward(dout, cache):
    """Вычисляет обратный проход для аффинного слоя.

    Входные данные:
    - dout: градиент, пришедший сверху (upstream), формы (N, M)
    - cache: кортеж из:
      - x: входные данные формы (N, d_1, ..., d_k)
      - w: веса формы (D, M)
      - b: смещения формы (M,)

    Возвращает кортеж:
    - dx: градиент по x формы (N, d_1, ..., d_k)
    - dw: градиент по w формы (D, M)
    - db: градиент по b формы (M,)
    """
    x, w, b = cache
    dx, dw, db = None, None, None
    # Реализация из лабораторной работы 1.
    x_rows = x.reshape(x.shape[0], -1)  # (N, D)
    # out = x_rows @ w + b, поэтому:
    dx = dout.dot(w.T).reshape(x.shape)  # (N, D) -> исходная форма x
    dw = x_rows.T.dot(dout)              # (D, M)
    db = dout.sum(axis=0)                # (M,): b прибавлялся к каждому примеру
    return dx, dw, db


def relu_forward(x):
    """Вычисляет прямой проход для слоя ReLU (rectified linear units).

    Входные данные:
    - x: входные данные произвольной формы

    Возвращает кортеж:
    - out: выход той же формы, что и x
    - cache: x
    """
    out = None
    # Реализация из лабораторной работы 1.
    out = np.maximum(0, x)
    cache = x
    return out, cache


def relu_backward(dout, cache):
    """Вычисляет обратный проход для слоя ReLU (rectified linear units).

    Входные данные:
    - dout: градиенты, пришедшие сверху (upstream), произвольной формы
    - cache: вход x той же формы, что и dout

    Возвращает:
    - dx: градиент по x
    """
    dx, x = None, cache
    # Реализация из лабораторной работы 1.
    # Градиент проходит только там, где вход был положительным
    dx = dout * (x > 0)
    return dx


def softmax_loss(x, y):
    """Вычисляет значение функции потерь и градиент для softmax-классификатора.

    Входные данные:
    - x: входные данные формы (N, C), где x[i, j] — оценка (score) j-го
      класса для i-го входа.
    - y: вектор меток формы (N,), где y[i] — метка для x[i] и
      0 <= y[i] < C

    Возвращает кортеж:
    - loss: скаляр — значение функции потерь
    - dx: градиент функции потерь по x
    """
    loss, dx = None, None

    # Реализация из лабораторной работы 1.
    N = x.shape[0]
    # Вычитаем максимум в каждой строке для численной устойчивости:
    # softmax от этого не меняется, а exp не переполняется
    shifted = x - np.max(x, axis=1, keepdims=True)
    # Логарифмы вероятностей: log p = s - log(sum(exp(s)))
    log_probs = shifted - np.log(np.sum(np.exp(shifted), axis=1, keepdims=True))

    # Средняя по батчу кросс-энтропия: -log p верного класса
    loss = -np.mean(log_probs[np.arange(N), y])

    # Градиент: (p - one_hot(y)) / N, где p — вероятности классов
    dx = np.exp(log_probs)
    dx[np.arange(N), y] -= 1
    dx /= N
    return loss, dx


def batchnorm_forward(x, gamma, beta, bn_param):
    """Прямой проход для батч-нормализации.

    Во время обучения выборочное среднее и выборочная дисперсия
    (неисправленная, то есть с делением на N, а не на N - 1) вычисляются по
    статистикам мини-батча и используются для нормализации входных данных.
    Кроме того, во время обучения для каждого признака поддерживаются
    скользящее среднее и скользящая дисперсия (с экспоненциальным
    затуханием); именно они используются для нормализации данных во время
    тестирования.

    На каждом шаге скользящие среднее и дисперсия обновляются с
    экспоненциальным затуханием, которое задаётся параметром momentum:

    running_mean = momentum * running_mean + (1 - momentum) * sample_mean
    running_var = momentum * running_var + (1 - momentum) * sample_var

    Обратите внимание: в статье о батч-нормализации для этапа тестирования
    предлагается другой подход — выборочные среднее и дисперсию каждого
    признака вычисляют по большому числу обучающих изображений, а не с
    помощью скользящего среднего. В этой реализации вместо этого
    используются скользящие средние, поскольку они не требуют
    дополнительного этапа оценивания; реализация батч-нормализации в torch7
    тоже использует скользящие средние.

    Входные данные:
    - x: данные формы (N, D)
    - gamma: параметр масштаба формы (D,)
    - beta: параметр сдвига формы (D,)
    - bn_param: словарь со следующими ключами:
      - mode: 'train' или 'test'; обязательный ключ
      - eps: константа для численной устойчивости
      - momentum: константа для скользящего среднего / дисперсии.
      - running_mean: массив формы (D,) — скользящее среднее признаков
      - running_var: массив формы (D,) — скользящая дисперсия признаков

    Возвращает кортеж:
    - out: выход формы (N, D)
    - cache: кортеж значений, необходимых для обратного прохода
    """
    mode = bn_param["mode"]
    eps = bn_param.get("eps", 1e-5)
    momentum = bn_param.get("momentum", 0.9)

    N, D = x.shape
    running_mean = bn_param.get("running_mean", np.zeros(D, dtype=x.dtype))
    running_var = bn_param.get("running_var", np.zeros(D, dtype=x.dtype))

    out, cache = None, None
    if mode == "train":
        #######################################################################
        # TODO: Реализуйте прямой проход батч-нормализации в режиме обучения. #
        # По статистикам мини-батча вычислите среднее и дисперсию, с их       #
        # помощью нормализуйте входные данные, а затем масштабируйте и        #
        # сдвиньте нормализованные данные с помощью gamma и beta.             #
        #                                                                     #
        # Результат сохраните в переменной out. Все промежуточные значения,   #
        # которые понадобятся для обратного прохода, сохраните в переменной   #
        # cache.                                                              #
        #                                                                     #
        # Кроме того, с помощью вычисленных выборочных среднего и дисперсии   #
        # и переменной momentum обновите скользящие среднее и дисперсию,      #
        # сохранив результат в переменных running_mean и running_var.         #
        #                                                                     #
        # Обратите внимание: хотя отслеживается скользящая дисперсия,         #
        # нормализовать данные нужно с помощью стандартного отклонения        #
        # (квадратного корня из дисперсии)!                                   #
        # Может пригодиться оригинальная статья                               #
        # (https://arxiv.org/abs/1502.03167).                                 #
        #######################################################################
        mean = x.mean(axis=0)
        var = x.var(axis=0)
        centered = x - mean
        inv_std = 1.0 / np.sqrt(var + eps)
        xhat = centered * inv_std
        out = gamma * xhat + beta
        cache = (centered, inv_std, xhat, gamma)
        running_mean = momentum * running_mean + (1 - momentum) * mean
        running_var = momentum * running_var + (1 - momentum) * var
        #######################################################################
        #                          КОНЕЦ ВАШЕГО КОДА                          #
        #######################################################################
    elif mode == "test":
        #######################################################################
        # TODO: Реализуйте прямой проход батч-нормализации в режиме           #
        # тестирования. С помощью скользящих среднего и дисперсии             #
        # нормализуйте входные данные, а затем масштабируйте и сдвиньте       #
        # нормализованные данные с помощью gamma и beta. Результат сохраните  #
        # в переменной out.                                                   #
        #######################################################################
        out = gamma * (x - running_mean) / np.sqrt(running_var + eps) + beta
        #######################################################################
        #                          КОНЕЦ ВАШЕГО КОДА                          #
        #######################################################################
    else:
        raise ValueError('Недопустимый режим батч-нормализации "%s"' % mode)

    # Сохраняем обновлённые скользящие средние обратно в bn_param
    bn_param["running_mean"] = running_mean
    bn_param["running_var"] = running_var

    return out, cache


def batchnorm_backward(dout, cache):
    """Обратный проход для батч-нормализации.

    В этой реализации нужно нарисовать на бумаге вычислительный граф
    батч-нормализации и распространить градиенты в обратном направлении
    через его промежуточные узлы.

    Входные данные:
    - dout: градиенты, пришедшие сверху (upstream), формы (N, D)
    - cache: переменная с промежуточными значениями из batchnorm_forward.

    Возвращает кортеж:
    - dx: градиент по входам x формы (N, D)
    - dgamma: градиент по параметру масштаба gamma формы (D,)
    - dbeta: градиент по параметру сдвига beta формы (D,)
    """
    dx, dgamma, dbeta = None, None, None
    ###########################################################################
    # TODO: Реализуйте обратный проход батч-нормализации. Сохраните           #
    # результаты в переменных dx, dgamma и dbeta.                             #
    # Может пригодиться оригинальная статья                                   #
    # (https://arxiv.org/abs/1502.03167).                                     #
    ###########################################################################

    centered, inv_std, xhat, gamma = cache
    N = dout.shape[0]
    dbeta = dout.sum(axis=0)
    dgamma = (dout * xhat).sum(axis=0)
    dxhat = dout * gamma
    dvar = (-0.5 * dxhat * centered * inv_std**3).sum(axis=0)
    dmean = (-dxhat * inv_std).sum(axis=0) - 2 * dvar * centered.mean(axis=0)
    dx = dxhat * inv_std + 2 * centered * dvar / N + dmean / N

    ###########################################################################
    #                            КОНЕЦ ВАШЕГО КОДА                            #
    ###########################################################################

    return dx, dgamma, dbeta


